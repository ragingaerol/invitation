create table if not exists public.rsvps (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 100),
  attending boolean not null,
  created_at timestamptz not null default now()
);

alter table public.rsvps enable row level security;

grant usage on schema public to anon;
grant select, insert on public.rsvps to anon;
grant usage, select on sequence public.rsvps_id_seq to anon;

drop policy if exists "Public can submit RSVPs" on public.rsvps;
create policy "Public can submit RSVPs"
  on public.rsvps
  for insert
  to anon
  with check (true);

drop policy if exists "Public can view RSVPs" on public.rsvps;
create policy "Public can view RSVPs"
  on public.rsvps
  for select
  to anon
  using (true);
